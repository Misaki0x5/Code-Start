create or replace function public.validate_student_code(
  p_code text,
  p_state text,
  p_lga text,
  p_school text
) returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.student_access_codes c
    where upper(trim(c.code)) = upper(trim(p_code))
      and lower(regexp_replace(trim(c.state), '\s+', ' ', 'g')) = lower(regexp_replace(trim(p_state), '\s+', ' ', 'g'))
      and lower(regexp_replace(trim(c.lga), '\s+', ' ', 'g')) = lower(regexp_replace(trim(p_lga), '\s+', ' ', 'g'))
      and lower(regexp_replace(trim(c.school), '\s+', ' ', 'g')) = lower(regexp_replace(trim(p_school), '\s+', ' ', 'g'))
  );
$$;

create or replace function public.create_profile_for_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_role text := coalesce(new.raw_user_meta_data->>'role', 'student');
  v_teacher_id uuid;
  v_teacher_email text;
  v_state text := coalesce(new.raw_user_meta_data->>'state', '');
  v_code text := coalesce(new.raw_user_meta_data->>'access_code', '');
  v_expected_teacher_code text;
begin
  if v_role not in ('student', 'teacher') then
    raise exception 'Invalid account role';
  end if;

  if v_role = 'teacher' then
    if upper(v_state) like '%ABUJA%' or upper(v_state) like '%FEDERAL CAPITAL%' or upper(v_state) = 'FCT' then
      v_expected_teacher_code := 'ABUJA-TEACH';
    else
      v_expected_teacher_code := upper(regexp_replace(v_state, '[^A-Za-z]', '', 'g')) || '-TEACH';
    end if;
    if upper(v_code) <> v_expected_teacher_code then
      raise exception 'Invalid teacher registration code';
    end if;
  else
    select c.teacher_id, p.email into v_teacher_id, v_teacher_email
    from public.student_access_codes c
    join public.profiles p on p.id = c.teacher_id
    where upper(trim(c.code)) = upper(trim(v_code))
      and lower(regexp_replace(trim(c.state), '\s+', ' ', 'g')) = lower(regexp_replace(trim(coalesce(new.raw_user_meta_data->>'state','')), '\s+', ' ', 'g'))
      and lower(regexp_replace(trim(c.lga), '\s+', ' ', 'g')) = lower(regexp_replace(trim(coalesce(new.raw_user_meta_data->>'lga','')), '\s+', ' ', 'g'))
      and lower(regexp_replace(trim(c.school), '\s+', ' ', 'g')) = lower(regexp_replace(trim(coalesce(new.raw_user_meta_data->>'school','')), '\s+', ' ', 'g'))
    limit 1;
    if v_teacher_id is null then
      raise exception 'Invalid student access code or school details';
    end if;
  end if;

  insert into public.profiles(id, email, name, role, age, level, state, lga, school, approved, teacher_id, teacher_email, last_active)
  values (
    new.id,
    lower(new.email),
    coalesce(new.raw_user_meta_data->>'name', split_part(new.email, '@', 1)),
    v_role,
    nullif(new.raw_user_meta_data->>'age', '')::integer,
    nullif(new.raw_user_meta_data->>'level', ''),
    nullif(new.raw_user_meta_data->>'state', ''),
    nullif(new.raw_user_meta_data->>'lga', ''),
    nullif(new.raw_user_meta_data->>'school', ''),
    v_role = 'teacher' or v_teacher_id is not null,
    v_teacher_id,
    v_teacher_email,
    (extract(epoch from now()) * 1000)::bigint
  );
  insert into public.private_data(user_id) values (new.id);
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_codestart on auth.users;
create trigger on_auth_user_created_codestart
  after insert on auth.users
  for each row execute procedure public.create_profile_for_new_auth_user();

create or replace function public.prevent_profile_privilege_changes()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if auth.uid() = old.id and (new.role <> old.role or new.teacher_id is distinct from old.teacher_id or new.approved is distinct from old.approved or new.email <> old.email) then
    raise exception 'Account role and teacher approval cannot be changed by the account owner';
  end if;
  return new;
end;
$$;

drop trigger if exists prevent_profile_privilege_changes on public.profiles;
create trigger prevent_profile_privilege_changes
  before update on public.profiles
  for each row execute procedure public.prevent_profile_privilege_changes();

create or replace function public.guard_assignment_updates()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if auth.uid() = old.student_id then
    if new.teacher_id <> old.teacher_id or new.student_id <> old.student_id or new.title <> old.title or new.question <> old.question or new.score is distinct from old.score or new.feedback <> old.feedback or new.marked_at is distinct from old.marked_at then
      raise exception 'Students may only submit an assignment answer';
    end if;
  elsif auth.uid() = old.teacher_id then
    if new.teacher_id <> old.teacher_id or new.student_id <> old.student_id or new.title <> old.title or new.question <> old.question or new.answer <> old.answer or new.submitted_at is distinct from old.submitted_at then
      raise exception 'Teachers may only mark submitted work';
    end if;
  else
    raise exception 'Not an assignment participant';
  end if;
  return new;
end;
$$;

drop trigger if exists guard_assignment_updates on public.assignments;
create trigger guard_assignment_updates
  before update on public.assignments
  for each row execute procedure public.guard_assignment_updates();

