create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  name text not null,
  role text not null check (role in ('student', 'teacher')),
  age integer,
  level text,
  state text,
  lga text,
  school text,
  approved boolean not null default false,
  teacher_id uuid references public.profiles(id) on delete set null,
  teacher_email text,
  progress jsonb not null default '{}'::jsonb,
  questions_asked integer not null default 0,
  last_active bigint,
  created_at timestamptz not null default now()
);

create table if not exists public.private_data (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  data jsonb not null default '{}'::jsonb
);

alter table public.profiles add column if not exists teacher_email text;

create table if not exists public.login_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null check (role in ('student', 'teacher')),
  created_at bigint not null
);

create table if not exists public.student_access_codes (
  id text primary key,
  teacher_id uuid not null references public.profiles(id) on delete cascade,
  code text not null unique,
  state text not null,
  lga text not null,
  school text not null,
  created_at bigint not null
);

create table if not exists public.inbox_messages (
  id text primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  teacher_id uuid not null references public.profiles(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  sender_role text not null check (sender_role in ('student', 'teacher')),
  sender_name text not null,
  message text not null,
  created_at bigint not null
